public class Variables {
    public static void main(String[] args) {
        byte b = 11;
        float f = 12.5f;
        int num = 12;
        char c = 'A';
        boolean bool = true;
        short s = 100;
        long l = 1000L;
        double d = 12.5;
        System.out.println(b+" "+num+" "+f+" "+c+" "+bool+" "+s+" "+l+" "+d);
    }
}
